// Regenerate the offline SVG paths; no map library is shipped to the app.
import { readFile, writeFile } from 'node:fs/promises';

const sourceUrl = 'https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/states-albers-10m.json';
const response = await fetch(sourceUrl);
if (!response.ok) throw new Error(`Map download failed: ${response.status}`);
const topology = await response.json();
const model = await readFile(new URL('../src/fifty-states-model.ts', import.meta.url), 'utf8');
const codes = new Map(Array.from(model.matchAll(/\['([A-Z]{2})', '([^']+)'\]/g), m => [m[2], m[1]]));
const arcs = topology.arcs.map(arc => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => {
    x += dx; y += dy;
    return [x * topology.transform.scale[0] + topology.transform.translate[0], y * topology.transform.scale[1] + topology.transform.translate[1]];
  });
});
const points = [];
function ringPath(indices) {
  const ring = [];
  for (const index of indices) {
    const arc = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
    ring.push(...(ring.length ? arc.slice(1) : arc));
  }
  points.push(...ring);
  return ring.map(([x, y], index) => `${index ? 'L' : 'M'}${+x.toFixed(2)},${+y.toFixed(2)}`).join('') + 'Z';
}
const paths = topology.objects.states.geometries.flatMap(geometry => {
  const code = codes.get(geometry.properties.name);
  if (!code) return [];
  const polygons = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.arcs;
  return [[code, polygons.flatMap(polygon => polygon.map(ringPath)).join('')]];
}).sort(([a], [b]) => a.localeCompare(b));
if (paths.length !== 50) throw new Error(`Expected fifty states, received ${paths.length}`);
const xs = points.map(p => p[0]), ys = points.map(p => p[1]);
const left = Math.floor(Math.min(...xs)) - 4, top = Math.floor(Math.min(...ys)) - 4;
const width = Math.ceil(Math.max(...xs)) + 4 - left, height = Math.ceil(Math.max(...ys)) + 4 - top;
const output = `// Generated by scripts/generate-fifty-states-map.mjs. Do not hand-edit.\n// us-atlas 3.0.1 (ISC), U.S. Census Bureau 2017 cartography, Albers USA projection.\n// Source: ${sourceUrl}\n// Includes Alaska/Hawaii insets; static geometry works entirely offline.\nimport type { USStateCode } from './fifty-states-model';\n\nexport const US_STATES_MAP_VIEW_BOX = '${left} ${top} ${width} ${height}' as const;\nexport const US_STATES_MAP_ASPECT_RATIO = ${width} / ${height};\n\nexport const US_STATE_PATHS: Readonly<Record<USStateCode, string>> = {\n${paths.map(([code, path]) => `  ${code}: ${JSON.stringify(path)},`).join('\n')}\n};\n`;
await writeFile(new URL('../src/fifty-states-map-data.ts', import.meta.url), output);
console.log(`Generated ${paths.length} projected states; viewBox ${left} ${top} ${width} ${height}; ${output.length} bytes.`);
